const sira = (n) => {
  const s = String(n).trim();
  if (!/^\d+$/.test(s)) return s;
  const k = Number(s) % 100, b = Number(s) % 10;
  return s + (k >= 11 && k <= 13 ? "th" : b === 1 ? "st" : b === 2 ? "nd" : b === 3 ? "rd" : "th");
};
const cogul = (n, tekil, cogulu = `${tekil}s`) => `${n} ${String(n).trim() === "1" ? tekil : cogulu}`;

